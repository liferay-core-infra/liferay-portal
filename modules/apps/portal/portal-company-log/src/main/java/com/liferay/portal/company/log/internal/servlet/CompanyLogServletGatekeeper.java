package com.liferay.portal.company.log.internal.servlet;

import com.liferay.portal.kernel.util.GetterUtil;
import com.liferay.portal.kernel.util.PropsKeys;
import com.liferay.portal.kernel.util.PropsUtil;

import org.osgi.service.component.ComponentContext;
import org.osgi.service.component.annotations.Activate;
import org.osgi.service.component.annotations.Component;

/**
 * @author Hai Yu
 */
@Component(immediate = true, service = {})
public class CompanyLogServletGatekeeper {

	@Activate
	protected void activate(ComponentContext componentContext) {
		if (GetterUtil.getBoolean(
				PropsUtil.get(PropsKeys.COMPANY_LOG_ENABLED))) {

			componentContext.enableComponent(CompanyLogServlet.class.getName());
		}
	}

}